#!/usr/bin/env node
/*
 * Regenerates assets/js/credentials.js for the admin sign-in.
 *
 *   node tools/set-password.mjs "Leadership" "your-new-password"
 *
 * The password itself is never written to disk or to the repository — only a
 * salted PBKDF2 hash of it, which the browser recomputes at sign-in.
 */
import { pbkdf2Sync, randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ITERATIONS = 250000;
const KEY_LENGTH = 32;

const [user, password] = process.argv.slice(2);
if (!user || !password) {
  console.error('Usage: node tools/set-password.mjs "<user name>" "<password>"');
  process.exit(1);
}

const salt = randomBytes(16);
const secret = `${user.trim().toLowerCase()}:${password}`;
const hash = pbkdf2Sync(secret, salt, ITERATIONS, KEY_LENGTH, "sha256");

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "assets", "js", "credentials.js");
writeFileSync(
  out,
  `/* Generated by tools/set-password.mjs — do not edit by hand.
   Salted PBKDF2-SHA256 hash of the admin sign-in. The password is not
   recoverable from this file; run the script again to change it. */

window.LW_ADMIN_CREDENTIALS = {
  salt: "${salt.toString("base64")}",
  hash: "${hash.toString("base64")}",
  iterations: ${ITERATIONS}
};
`
);

console.log(`Wrote ${out}`);
console.log(`User name: ${user.trim()}`);
console.log("Password stored as a salted hash. Keep the password itself somewhere safe.");
